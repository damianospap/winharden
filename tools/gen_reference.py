#!/usr/bin/env python3
"""Generate docs/REFERENCE.md from the manifests.

  python3 -I tools/gen_reference.py           write docs/REFERENCE.md
  python3 -I tools/gen_reference.py --check   exit 1 if the file is out of date

The output is deterministic, so a test can compare it with the committed file.
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import validate_manifests as V  # noqa: E402

OUT = ROOT / "docs" / "REFERENCE.md"
PROFILES = {1: "Classic", 2: "Private", 3: "Deep"}
HOME_ORDER = ("verified", "expected", "unverified", "na")


def load_docs(manifests: Path) -> list[tuple[str, dict]]:
    return [(f.name, V.load_json(f)) for f in sorted(manifests.glob("*.json"))]


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|")


def render(docs: list[tuple[str, dict]]) -> str:
    entries = [(d["module"], e) for _, d in docs for e in d["entries"]]
    out = [
        "# Manifest reference",
        "",
        "Generated by `tools/gen_reference.py` from `manifests/*.json`. Do not edit by hand.",
        "",
        "## Profiles (nested: profile N applies every entry with min_profile <= N)",
        "",
        "| Profile | Name | Entries | enforce | once (one-time clean-up) | attest or manual |",
        "|---|---|---|---|---|---|",
    ]
    for n, name in PROFILES.items():
        chosen = [e for _, e in entries if e["min_profile"] <= n and "opt_in" not in e]
        enforce = sum(e["mode"] == "enforce" for e in chosen)
        once = sum(e["mode"] == "once" for e in chosen)
        out.append(f"| {n} | {name} | {len(chosen)} | {enforce} | {once} | {len(chosen) - enforce - once} |")
    out += ["", "## Evidence on Windows 11 Home", "", "| home_effective | Entries |", "|---|---|"]
    for key in HOME_ORDER:
        out.append(f"| {key} | {sum(e['home_effective'] == key for _, e in entries)} |")
    for module in dict.fromkeys(m for m, _ in entries):
        out += ["", f"## {module}", "",
                "| ID | Title | Tier | Profile | Mode | Home | Risk | Channel | Rollback |",
                "|---|---|---|---|---|---|---|---|---|"]
        for m, e in entries:
            if m == module:
                out.append("| " + " | ".join(_cell(x) for x in (
                    e["id"], e["title"], e["tier"], e["min_profile"], e["mode"], e["home_effective"],
                    e["risk"], e["channel_class"], e["rollback"]["reversibility"])) + " |")
    out += ["", "## Needs attention", ""]
    def requirement(e: dict) -> str:
        return f"`{e['id']}` ({e['requires_hardware']})"

    def opt_in(e: dict) -> str:
        return f"`{e['id']}` (-OptIn {e['opt_in']})"

    groups = (
        ("Manual steps (the tool only reports them)", lambda e: e["mode"] == "manual", None),
        ("One-time clean-up (mode once: files are deleted and cannot be restored)", lambda e: e["mode"] == "once", None),
        ("Partial rollback", lambda e: e["rollback"]["reversibility"] == "partial", None),
        ("Needs a reboot", lambda e: e.get("flags", {}).get("requires_reboot", False), None),
        ("Servicing-adjacent", lambda e: e.get("flags", {}).get("servicing_adjacent", False), None),
        ("Deletes user data (skipped unless the plan is made with -AcceptDataLoss)",
         lambda e: e.get("flags", {}).get("deletes_user_data", False), None),
        ("Blocked unless the system meets a requirement (secure_boot, uefi, tpm2, virtualization, defender_active)",
         lambda e: "requires_hardware" in e, requirement),
        ("Opt-in only (left out of every profile unless the run names the tag)", lambda e: "opt_in" in e, opt_in),
    )
    for title, pick, fmt in groups:
        items = [fmt(e) if fmt else f"`{e['id']}`" for _, e in entries if pick(e)]
        out.append(f"- **{title}:** " + (", ".join(items) if items else "none"))
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate docs/REFERENCE.md.")
    ap.add_argument("--check", action="store_true", help="fail if docs/REFERENCE.md is out of date")
    args = ap.parse_args(argv)
    text = render(load_docs(ROOT / "manifests"))
    if args.check:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/REFERENCE.md is out of date: run python3 -I tools/gen_reference.py", file=sys.stderr)
            return 1
        print("OK: docs/REFERENCE.md is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
